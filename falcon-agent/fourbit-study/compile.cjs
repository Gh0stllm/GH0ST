const fs=require('fs'),path=require('path');
const solc=require('../../contract-benchmark/node_modules/solc');
const sources=Object.fromEntries(fs.readdirSync(__dirname).filter(f=>f.endsWith('.sol')).map(f=>[f,{content:fs.readFileSync(path.join(__dirname,f),'utf8')}]));
const runs=Number(process.argv[2]||1000000);
const settings={optimizer:{enabled:true,runs},viaIR:true,evmVersion:'cancun',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}};
const result=JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources,settings})));
for(const e of result.errors||[])process.stderr.write(e.formattedMessage+'\n');
if((result.errors||[]).some(e=>e.severity==='error'))process.exit(1);
const contracts=Object.assign({},...Object.values(result.contracts));
fs.writeFileSync(path.join(__dirname,`compiled-${runs}.json`),JSON.stringify({compiler:solc.version(),settings,contracts},null,2)+'\n');
console.log(JSON.stringify({runs,compiler:solc.version(),bytes:Object.fromEntries(Object.entries(contracts).map(([n,c])=>[n,c.evm.deployedBytecode.object.length/2]))}));
