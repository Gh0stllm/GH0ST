"""Verify the existing full TinyStories export and prepare a flat, hashed fixture.

Weights stay outside source control. This does not fetch, publish or deploy them.
"""
from pathlib import Path
import argparse
import hashlib
import json

HERE = Path(__file__).resolve().parent
REVISION = "77f1b168e219585646439073245fe87e56b3023e"
CHECKPOINT = "07f9609ea882b8163ff3b23d40e2b82cb715d409631beb15c84b164f3877dae7"
FLAT_SHA256 = "6dc6dd216d0c4b12b81b0844244423e53bb8d7e4c726b8e6205683708971ef1f"
ARCHITECTURE = {"width":64,"layers":8,"heads":16,"head_width":4,"mlp_width":256,
    "vocabulary":50257,"native_context":2048,"context_tokens":64,
    "tied_embedding":True,"attention_scaling":"none","native_local_window":256}

def prepare(export_dir):
    source = export_dir / "data"
    manifest = json.loads((source / "manifest.json").read_text())
    if (manifest["model_id"], manifest["revision"], manifest["checkpoint_sha256"],
        manifest["unique_parameter_count"]) != ("roneneldan/TinyStories-1M", REVISION, CHECKPOINT, 3745984):
        raise ValueError("Wrong pinned pretrained model")
    if len(manifest["tensors"]) != 53:
        raise ValueError("Incomplete model tensor set")
    if manifest["architecture"] != ARCHITECTURE:
        raise ValueError("Unexpected model architecture or context policy")
    layout=[("embedding",50257,64,68),("position",2048,64,256),("layernorm",1,64,512)]
    for _ in range(8):
        layout.extend([("layernorm",1,64,512),("layernorm",1,64,512),
            ("linear",192,64,72),("linear",64,64,72),("linear",256,64,72),("linear",64,256,264)])
    layout.extend([("exp_lut",1,4097,16388),("tanh_lut",1,2049,4098)])
    blob = bytearray()
    tensors = []
    for index, tensor in enumerate(manifest["tensors"]):
        payload = (source / tensor["file"]).read_bytes()
        if tuple(tensor[k] for k in ("kind","rows","width","row_bytes")) != layout[index]:
            raise ValueError(f"Unexpected tensor layout {index}")
        if len(payload) != tensor["rows"]*tensor["row_bytes"]:
            raise ValueError(f"Unexpected tensor size {index}")
        if tensor["id"] != index or len(payload) != tensor["bytes"] or hashlib.sha256(payload).hexdigest() != tensor["sha256"]:
            raise ValueError(f"Tensor integrity failure {index}")
        tensors.append({**{key: tensor[key] for key in ("id", "name", "kind", "rows", "width", "row_bytes", "bytes", "sha256")}, "offset": len(blob)})
        blob.extend(payload)
    digest = hashlib.sha256(blob).hexdigest()
    if digest != FLAT_SHA256:
        raise ValueError("Model bytes do not match the independently pinned integer export")
    cache = HERE / ".cache"
    cache.mkdir(exist_ok=True)
    (cache / "model.bin").write_bytes(blob)
    header = "// Generated by prepare_model.py; weights are separate input data.\n#pragma once\n#include <cstdint>\n"
    header += f"constexpr uint32_t MODEL_BYTES = {len(blob)};\n"
    header += "constexpr uint32_t OFFSETS[53] = {" + ",".join(str(t["offset"]) for t in tensors) + "};\n"
    header += "constexpr uint8_t EXPECTED_MODEL_SHA256[32] = {" + ",".join(str(b) for b in bytes.fromhex(digest)) + "};\n"
    (cache / "model_layout.h").write_text(header)
    descriptor = {"model": manifest["model_id"], "revision": REVISION,
        "checkpointSHA256": CHECKPOINT, "parameters": 3745984,
        "arithmetic": "documented INT8/Q12 approximation, not FP32 identity",
        "architecture": manifest["architecture"], "modelBytes": len(blob),
        "flatModelSHA256": digest, "tensors": tensors,
        "weightsRedistributed": False, "publicLicenseReviewComplete": False}
    (HERE / "model-descriptor.json").write_text(json.dumps(descriptor, indent=2) + "\n")
    print(json.dumps({"modelBytes": len(blob), "flatModelSHA256": digest, "tensorsVerified": len(tensors)}))

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export-dir", type=Path, default=HERE.parents[4] / "output/arc-tinystories-20261025/tinystories3746k")
    prepare(parser.parse_args().export_dir)
