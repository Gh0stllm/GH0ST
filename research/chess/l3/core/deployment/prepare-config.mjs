// Pure SDK configuration preparation. No provider, account, signer or RPC exists.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import { build, version as esbuildVersion } from 'esbuild';
import { getAddress, keccak256, toUtf8Bytes, ZeroAddress } from 'ethers';

const root = dirname(fileURLToPath(import.meta.url));
const pin = JSON.parse(readFileSync(resolve(root, 'sdk-source.json')));
const intent = JSON.parse(readFileSync(resolve(root, 'intent.json')));
const sdk = resolve(root, `.cache/arbitrum-chain-sdk-${pin.commit}/src`);
const output = resolve(root, '.cache/sdk-pure.mjs');
const expectedSources = {
  'prepareChainConfigSortKeys.ts': 'c8c7a1f299fe7c24a8f80ff8b30acc232410c7408389113cab5ef1aadfb28b63',
  'prepareChainConfig.ts': 'cdee1e43fe3d47de62755025377a6ddb59faf267d6d5d3059d5a7eed5c6e65f1',
  'wasmModuleRoot.ts': 'c0cb7b1cce6e1b25064127e806454f3492454ea999a6af726e6a10ec48a0f486',
};
for (const [name, hash] of Object.entries(expectedSources)) {
  if (createHash('sha256').update(readFileSync(resolve(sdk, name))).digest('hex') !== hash) throw Error('Pinned SDK helper source mismatch');
}
if (!Number.isSafeInteger(intent.childChainIdProposal) || intent.childChainIdProposal <= 0 || intent.childChainIdProposal === intent.parentChainId) throw Error('Invalid child chain ID');
if (getAddress(intent.chainOwnerProposal) === ZeroAddress) throw Error('Zero chain owner rejected');
mkdirSync(resolve(root, '.cache'), { recursive: true });
const entry = 'export {prepareChainConfig} from "./prepareChainConfig"; export {getConsensusReleaseByVersion} from "./wasmModuleRoot";';
const result = await build({
  stdin: { contents: entry,
    resolveDir: sdk, loader: 'ts' },
  bundle: true, platform: 'node', format: 'esm', outfile: output, metafile: true,
});
if (Object.values(result.metafile.outputs).some(x => x.imports.length)) throw Error('Unexpected runtime dependency in pure SDK helpers');
const sourceHashes = Object.fromEntries(Object.keys(result.metafile.inputs).filter(p => p !== '<stdin>').map(p => {
  const full = resolve(process.cwd(), p);
  return [full.slice(sdk.length + 1), createHash('sha256').update(readFileSync(full)).digest('hex')];
}));
if (JSON.stringify(Object.keys(sourceHashes).sort()) !== JSON.stringify(Object.keys(expectedSources).sort())) throw Error('Unexpected SDK helper dependency');
for (const [name, hash] of Object.entries(sourceHashes)) {
  if (hash !== expectedSources[name]) throw Error('Bundled SDK helper source mismatch');
}
const helpers = await import(pathToFileURL(output));
const release = helpers.getConsensusReleaseByVersion(intent.initialArbOSVersion);
if (release?.wasmModuleRoot !== intent.wasmModuleRoot || release.maxArbOSVersion !== 61) throw Error('Canonical consensus release mismatch');
if (intent.allowDebugPrecompiles !== false || intent.dataAvailabilityCommittee !== false) throw Error('Core requires standard non-debug Rollup');
const config = helpers.prepareChainConfig({
  chainId: intent.childChainIdProposal,
  arbitrum: { InitialChainOwner: getAddress(intent.chainOwnerProposal), InitialArbOSVersion: 61,
    DataAvailabilityCommittee: false },
});
if (config.arbitrum.AllowDebugPrecompiles !== false || config.arbitrum.MaxCodeSize !== 24576 || config.arbitrum.MaxInitCodeSize !== 49152) throw Error('Ordinary core limits changed');
const text = JSON.stringify(config, null, 2) + '\n';
writeFileSync(resolve(root, 'chain-config.proposed.json'), text);
const report = {
  scope: 'Unsigned proposal generated by exact pinned SDK pure helpers; not full deployment parameters or a deployed genesis',
  sdkCommit: pin.commit, sdkArchiveSHA256: pin.archiveSHA256, esbuildVersion,
  sourceHashes, entrySHA256: createHash('sha256').update(entry).digest('hex'),
  consensusVersion: release.version, officialWasmModuleRoot: release.wasmModuleRoot,
  chainConfigSHA256: createHash('sha256').update(text).digest('hex'),
  compactChainConfigKeccak256: keccak256(toUtf8Bytes(JSON.stringify(config))),
  parentChainId: intent.parentChainId, proposedChildChainId: config.chainId,
  nodeAndParentConnected: false, childChainIdRegistered: false,
  rpcRequestsMade: 0, accountOrWalletAccessed: false, transactionCalldataCreated: false,
  signatureOrBroadcastSupported: false, readyForMainnetSigning: false,
};
writeFileSync(resolve(root, 'evidence/sdk-config.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
