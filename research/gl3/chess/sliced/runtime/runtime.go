//go:embed .cache/sliced.wasm
var moduleBytes []byte

const PageSize = 4096
const MaxMemory = 768 * 1024 * 1024
const Quantum = 2048
const TargetNodes = 24000000

var ErrState = errors.New("invalid GL3 chess continuation")
var ctx = context.Background()
var sharedOnce sync.Once
var shared *Runtime
var sharedErr error

type Runtime struct {
	R       wazero.Runtime
	C       wazero.CompiledModule
	Globals []string
}
type VM struct {
	R *Runtime
	M api.Module
}
type Global struct {
	Name  string
	Value uint64
}
type Image struct {
	Memory  []byte
	Globals []Global
}
type Progress struct {
	Pending         bool
	Step            uint32
	Observed, Nodes uint64
	Depth           uint32
	Move            string
}

func Shared() (*Runtime, error) {
	sharedOnce.Do(func() { shared, sharedErr = New(false) })
	return shared, sharedErr
}
func New(interpreter bool) (*Runtime, error) {
	// The complete STF module root already commits the embedded program in
	// proof mode. Native startup verifies the generated identity once as well.
	if runtime.GOARCH != "wasm" && sha256.Sum256(moduleBytes) != ModuleSHA {
		return nil, ErrState
	}
	cfg := wazero.NewRuntimeConfig().WithMemoryLimitPages(MaxMemory / 65536)
	if interpreter || runtime.GOARCH == "wasm" {
		cfg = wazero.NewRuntimeConfigInterpreter().WithMemoryLimitPages(MaxMemory / 65536)
	}
	r := wazero.NewRuntimeWithConfig(ctx, cfg)
	c, e := r.CompileModule(ctx, moduleBytes)
	if e != nil {
		return nil, e
	}
	// All host functions trap. The engine may not read clocks, files or an oracle.
	builders := map[string]wazero.HostModuleBuilder{}
	for _, f := range c.ImportedFunctions() {
		mod, name, _ := f.Import()
		b := builders[mod]
		if b == nil {
			b = r.NewHostModuleBuilder(mod)
			builders[mod] = b
		}
		key := mod + "." + name
		b.NewFunctionBuilder().WithGoModuleFunction(api.GoModuleFunc(func(context.Context, api.Module, []uint64) { panic("forbidden engine host call: " + key) }), f.ParamTypes(), f.ResultTypes()).Export(name)
	}
	for _, b := range builders {
		if _, e = b.Instantiate(ctx); e != nil {
			return nil, e
		}
	}
	result := &Runtime{R: r, C: c}
	// Global names are generated by the pinned transform, in module order.
	result.Globals, e = globalExports(moduleBytes)
	if e != nil {
		return nil, e
	}
	return result, nil
}
func (r *Runtime) Close() { r.R.Close(ctx) }
func (r *Runtime) Instantiate() (*VM, error) {
	m, e := r.R.InstantiateModule(ctx, r.C, wazero.NewModuleConfig().WithName("").WithStartFunctions())
	if e != nil {
		return nil, e
	}
	return &VM{r, m}, nil
}
func (v *VM) Close() { v.M.Close(ctx) }
func (v *VM) Call(name string, args ...uint64) (uint64, error) {
	f := v.M.ExportedFunction(name)
	if f == nil {
		return 0, ErrState
	}
	a, e := f.Call(ctx, args...)
	if e != nil {
		return 0, e
	}
	if len(a) == 0 {
		return 0, nil
	}
	if len(a) != 1 {
		return 0, ErrState
	}
	return a[0], nil
}
func (v *VM) Init() error {
	if _, e := v.Call("_initialize"); e != nil {
		return e
	}
	_, e := v.Call("gl3_slice_init")
	return e
}
func (v *VM) Image() Image {
	m := v.M.Memory()
	b, _ := m.Read(0, m.Size())
	im := Image{Memory: bytes.Clone(b)}
	for _, name := range v.R.Globals {
		if g := v.M.ExportedGlobal(name); g != nil {
			im.Globals = append(im.Globals, Global{name, g.Get()})
		} else {
			panic(ErrState)
		}
	}
	return im
}
func (v *VM) Memory() []byte {
	m := v.M.Memory()
	b, ok := m.Read(0, m.Size())
	if !ok {
		panic(ErrState)
	}
	return b
}
func (v *VM) Globals() []Global {
	var result []Global
	for _, n := range v.R.Globals {
		if g := v.M.ExportedGlobal(n); g != nil {
			result = append(result, Global{n, g.Get()})
		} else {
			panic(ErrState)
		}
	}
	return result
}
func (v *VM) Restore(im Image) error {
	if len(im.Memory) == 0 || len(im.Memory) > MaxMemory || len(im.Memory)%65536 != 0 {
		return ErrState
	}
	m := v.M.Memory()
	if len(im.Memory) < int(m.Size()) {
		return ErrState
	}
	if n := (uint32(len(im.Memory)) - m.Size()) / 65536; n > 0 {
		if _, ok := m.Grow(n); !ok {
			return ErrState
		}
	}
	if !m.Write(0, im.Memory) {
		return ErrState
	}
	expected := v.Globals()
	if len(expected) != len(im.Globals) {
		return ErrState
	}
	for i, g := range im.Globals {
		if g.Name != expected[i].Name {
			return ErrState
		}
		target, ok := v.M.ExportedGlobal(g.Name).(api.MutableGlobal)
		if !ok {
			return ErrState
		}
		target.Set(g.Value)
	}
	return nil
}
func (v *VM) Begin(history string) (Progress, error) {
	if len(history) == 0 || len(history) > 8192 {
		return Progress{}, ErrState
	}
	p, e := v.Call("gl3_alloc", uint64(len(history)))
	if e != nil || p == 0 {
		return Progress{}, ErrState
	}
	if !v.M.Memory().Write(uint32(p), []byte(history)) {
		return Progress{}, ErrState
	}
	pending, e := v.Call("gl3_slice_begin", p, uint64(len(history)))
	if e != nil {
		return Progress{}, e
	}
	// The request buffer is not used by the suspended search; set_position copied it.
	if _, e = v.Call("gl3_free", p); e != nil {
		return Progress{}, e
	}
	return v.progress(pending)
}
func (v *VM) Advance() (Progress, error) {
	pending, e := v.Call("gl3_slice_advance")
	if e != nil {
		return Progress{}, e
	}
	return v.progress(pending)
}
func (v *VM) progress(p uint64) (Progress, error) {
	if p > 1 {
		return Progress{}, ErrState
	}
	r := Progress{Pending: p == 1}
	get := func(n string) uint64 {
		a, e := v.Call(n)
		if e != nil {
			panic(e)
		}
		return a
	}
	r.Step = uint32(get("gl3_slice_steps"))
	r.Observed = get("gl3_slice_observed")
	r.Nodes = get("gl3_slice_actual")
	r.Depth = uint32(get("gl3_slice_depth"))
	if !r.Pending {
		at := uint32(get("gl3_slice_best"))
		b, ok := v.M.Memory().Read(at, 8)
		if !ok {
			return r, ErrState
		}
		r.Move = string(bytes.SplitN(b, []byte{0}, 2)[0])
		if len(r.Move) < 4 || len(r.Move) > 5 || (r.Nodes < TargetNodes && r.Depth != 245) {
			return r, ErrState
		}
	}
	return r, nil
}
func (v *VM) Canonical() ([]byte, error) {
	p, e := v.Call("gl3_slice_canonical")
	if e != nil {
		return nil, e
	}
	n, e := v.Call("gl3_slice_canonical_size")
	if e != nil {
		return nil, e
	}
	b, ok := v.M.Memory().Read(uint32(p), uint32(n))
	if !ok {
		return nil, ErrState
	}
	return bytes.Clone(b), nil
}

// A domain-separated Merkle root binds every byte, memory length and globals.
// Internal trees let a small dirty set update the commitment without rehashing
// the complete engine memory on each slice.
type Tree struct {
	Leaves int
	Hashes [][32]byte
}

func leaf(i int, b []byte) [32]byte {
	h := sha256.New()
	h.Write([]byte("GL3_CHESS_VM_PAGE_V1"))
	var n [8]byte
	binary.LittleEndian.PutUint64(n[:], uint64(i))
	h.Write(n[:])
	h.Write(b)
	var out [32]byte
	copy(out[:], h.Sum(nil))
	return out
}
func parent(a, b [32]byte) [32]byte {
	var x [65]byte
	x[0] = 1
	copy(x[1:33], a[:])
	copy(x[33:], b[:])
	return sha256.Sum256(x[:])
}
func NewTree(memory []byte) *Tree {
	n := 1
	for n < (MaxMemory+PageSize-1)/PageSize {
		n *= 2
	}
	t := &Tree{n, make([][32]byte, n*2)}
	for i := 0; i < len(memory)/PageSize; i++ {
		t.Hashes[n+i] = leaf(i, memory[i*PageSize:(i+1)*PageSize])
	}
	for i := n - 1; i > 0; i-- {
		t.Hashes[i] = parent(t.Hashes[i*2], t.Hashes[i*2+1])
	}
	return t
}
func (t *Tree) Set(i int, b []byte) {
	at := t.Leaves + i
	t.Hashes[at] = leaf(i, b)
	for at /= 2; at > 0; at /= 2 {
		t.Hashes[at] = parent(t.Hashes[at*2], t.Hashes[at*2+1])
	}
}
func (t *Tree) SetLeaf(i int, b []byte) { t.Hashes[t.Leaves+i] = leaf(i, b) }

// Changed page indices arrive in ascending order. Merge shared ancestors once.
func (t *Tree) Flush(pages []int) {
	current := make([]int, len(pages))
	for i, p := range pages {
		current[i] = t.Leaves + p
	}
	for len(current) > 0 && current[0] > 1 {
		next := make([]int, 0, (len(current)+1)/2)
		last := -1
		for _, i := range current {
			p := i / 2
			if p == last {
				continue
			}
			last = p
			t.Hashes[p] = parent(t.Hashes[2*p], t.Hashes[2*p+1])
			next = append(next, p)
		}
		current = next
	}
}
func (t *Tree) Root(memoryBytes int, globals []Global) [32]byte {
	h := sha256.New()
	h.Write([]byte("GL3_CHESS_IMAGE_V1"))
	h.Write(ModuleSHA[:])
	h.Write(t.Hashes[1][:])
	var n [8]byte
	binary.LittleEndian.PutUint64(n[:], uint64(memoryBytes))
	h.Write(n[:])
	for _, g := range globals {
		h.Write([]byte(g.Name))
		h.Write([]byte{0})
		binary.LittleEndian.PutUint64(n[:], g.Value)
		h.Write(n[:])
	}
	var r [32]byte
	copy(r[:], h.Sum(nil))
	return r
}
func Diff(before, after []byte, fn func(int, []byte) error) error {
	if len(after) > MaxMemory || len(after)%PageSize != 0 || len(after) < len(before) {
		return ErrState
	}
	for at := 0; at < len(after); at += PageSize {
		page := after[at : at+PageSize]
		if at >= len(before) || !bytes.Equal(before[at:at+PageSize], page) {
			if e := fn(at/PageSize, page); e != nil {
				return e
			}
		}
	}
	return nil
}
func SortedGlobals(g []Global) bool {
	return sort.SliceIsSorted(g, func(i, j int) bool { return g[i].Name < g[j].Name })
}

// Read the export section instead of assuming a fixed global-index range.
func globalExports(b []byte) ([]string, error) {
	at := 8
	read := func(end int) (uint32, bool) {
		var n uint32
		for shift := uint(0); shift < 35; shift += 7 {
			if at >= end {
				return 0, false
			}
			x := b[at]
			at++
			n |= uint32(x&127) << shift
			if x < 128 {
				return n, true
			}
		}
		return 0, false
	}
	for at < len(b) {
		id := b[at]
		at++
		n, ok := read(len(b))
		if !ok || uint64(at)+uint64(n) > uint64(len(b)) {
			return nil, ErrState
		}
		end := at + int(n)
		if id != 7 {
			at = end
			continue
		}
		count, ok := read(end)
		if !ok {
			return nil, ErrState
		}
		var result []string
		for i := uint32(0); i < count; i++ {
			n, ok := read(end)
			if !ok || uint64(at)+uint64(n)+1 > uint64(end) {
				return nil, ErrState
			}
			name := string(b[at : at+int(n)])
			at += int(n)
			kind := b[at]
			at++
			if _, ok = read(end); !ok {
				return nil, ErrState
			}
			if kind == 3 && strings.HasPrefix(name, "gl3_global_") {
				result = append(result, name)
			}
		}
		if at != end || len(result) == 0 {
			return nil, ErrState
		}
		return result, nil
	}
	return nil, ErrState
}
